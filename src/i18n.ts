export function translate(locale: Locale, source: string): string {
  return locale === "zh-CN" ? (chinese[source] ?? source) : source;
}

export function readLocale(): Locale {
  try {
    return localStorage.getItem("lokvyn.locale") === "zh-CN" ? "zh-CN" : "en";
  } catch {
    return "en";
  }
}

export function saveLocale(locale: Locale) {
  try {
    localStorage.setItem("lokvyn.locale", locale);
  } catch {
    // The preference remains usable for this session when storage is unavailable.
  }
}
